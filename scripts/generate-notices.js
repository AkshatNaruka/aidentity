#!/usr/bin/env node

/**
 * Generate THIRD_PARTY_NOTICES.md from registry/sources.json.
 *
 * One block per upstream: attribution, license, what is vendored, and the
 * upstream license text when we have it. Re-run whenever sources change.
 *
 * Usage:
 *   node scripts/generate-notices.js
 */

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const OUT = path.join(ROOT, "THIRD_PARTY_NOTICES.md");
const sources = JSON.parse(fs.readFileSync(path.join(ROOT, "registry", "sources.json"), "utf8")).sources;

const registryPath = path.join(ROOT, "registry", "skills.json");
const registry = fs.existsSync(registryPath) ? JSON.parse(fs.readFileSync(registryPath, "utf8")) : { skills: [] };

const counts = {};
for (const skill of registry.skills) {
  counts[skill.source.key] = (counts[skill.source.key] || 0) + 1;
}

const LICENSE_NAMES = ["LICENSE", "LICENSE.txt", "LICENSE.md", "COPYING", "NOTICE"];

function readLicense(dir) {
  for (const name of LICENSE_NAMES) {
    const file = path.join(dir, name);
    if (fs.existsSync(file)) {
      const text = fs.readFileSync(file, "utf8").trim();
      if (text) return { name, text };
    }
  }
  return null;
}

const lines = [
  "# Third-Party Notices",
  "",
  "Aidentity is an index. Every skill belongs to its author and is used under the terms below.",
  "",
  "This file is generated by `node scripts/generate-notices.js`. Do not edit by hand.",
  "",
  "---",
  "",
];

for (const [key, source] of Object.entries(sources)) {
  const count = counts[key] || 0;
  const vendored = source.publish !== false && !source.firstParty;

  lines.push(`## ${source.author} — [${source.repo}](${source.url})`, "");
  lines.push(`- **License:** ${source.license}`);
  if (source.copyright) lines.push(`- **Copyright:** ${source.copyright}`);
  lines.push(`- **Entries indexed:** ${count}`);
  lines.push(`- **Content hosted here:** ${vendored ? "yes" : "no — pointer entries only"}`);
  if (source.notice) lines.push(`- **Notice:** ${source.notice}`);
  lines.push("");

  if (source.note) {
    lines.push(`> ${source.note}`, "");
  }

  if (vendored) {
    const license = readLicense(path.join(ROOT, "skills", key));
    if (license) {
      lines.push(`<details><summary>${license.name}</summary>`, "", "```", license.text, "```", "", "</details>", "");
    } else {
      lines.push(`_License text not found at \`skills/${key}/\`. Add the upstream license file before release._`, "");
    }
  }

  lines.push("---", "");
}

lines.push(
  "## Aidentity itself",
  "",
  "- Code (`cli/`, `site/`, `scripts/`): MIT. See `LICENSE`.",
  "- Registry data (`registry/*.json`): CC0 1.0. See `LICENSE-DATA`.",
  "- Original writing (`docs/`, `bundles/`): CC BY 4.0.",
  ""
);

fs.writeFileSync(OUT, lines.join("\n"));
console.log(`Wrote ${path.relative(ROOT, OUT)} (${Object.keys(sources).length} sources)`);

#!/usr/bin/env node
/**
 * Build the weekly registry report from validation and verification output.
 *
 *   node scripts/weekly-report.js /tmp/validation.json /tmp/verify.json
 *
 * Writes reports/<date>.md and reports/latest.md. Missing inputs are tolerated:
 * the report says "not run" instead of failing.
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const date = new Date().toISOString().slice(0, 10);

function read(file) {
  try {
    return JSON.parse(fs.readFileSync(file, "utf8"));
  } catch {
    return null;
  }
}

const validation = read(process.argv[2]);
const verify = read(process.argv[3]);
const catalog = read(path.join(ROOT, "registry", "catalog.json")) || { total: 0, by_type: {} };
const registry = read(path.join(ROOT, "registry", "skills.json")) || { total: 0, distributable: 0 };

const lines = [
  `# Registry report — ${date}`,
  "",
  `| | |`,
  `|---|---|`,
  `| Catalog entries | ${catalog.total} |`,
  `| Types | ${Object.entries(catalog.by_type || {}).map(([k, v]) => `${k}: ${v}`).join(", ")} |`,
  `| Skills | ${registry.total} (${registry.distributable} installable) |`,
  `| Validation | ${validation ? (validation.ok ? "passed" : `${validation.errors.length} errors`) : "not run"} |`,
  `| Upstream check | ${verify ? `${verify.ok}/${verify.total_sources} reachable` : "not run"} |`,
  "",
];

if (validation && validation.errors && validation.errors.length) {
  lines.push("## Validation errors", "");
  for (const error of validation.errors) lines.push(`- ${error}`);
  lines.push("");
}
if (validation && validation.warnings && validation.warnings.length) {
  lines.push("## Warnings", "");
  for (const warning of validation.warnings) lines.push(`- ${warning}`);
  lines.push("");
}
if (verify && verify.sources) {
  const dead = Object.entries(verify.sources).filter(([, value]) => !value.ok);
  lines.push("## Dead upstreams", "");
  if (!dead.length) lines.push("None.");
  else for (const [key, value] of dead) lines.push(`- \`${key}\` — ${value.url} (status ${value.status})`);
  lines.push("");
}

lines.push(
  "---",
  "",
  "Generated by `scripts/weekly-report.js`. Review the failures, fix them, then merge.",
  ""
);

const output = lines.join("\n");
fs.mkdirSync(path.join(ROOT, "reports"), { recursive: true });
fs.writeFileSync(path.join(ROOT, "reports", `${date}.md`), output);
fs.writeFileSync(path.join(ROOT, "reports", "latest.md"), output);
console.log(`Wrote reports/${date}.md`);
